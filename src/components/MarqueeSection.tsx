const ROW_1_ORIGINAL = ALL_IMAGES.slice(0, 11);
const ROW_2_ORIGINAL = ALL_IMAGES.slice(11);

// Tripled arrays for seamless scrolling
const ROW_1_IMAGES = [...ROW_1_ORIGINAL, ...ROW_1_ORIGINAL, ...ROW_1_ORIGINAL];
const ROW_2_IMAGES = [...ROW_2_ORIGINAL, ...ROW_2_ORIGINAL, ...ROW_2_ORIGINAL];

export const MarqueeSection: React.FC = () => {
  const sectionRef = useRef<HTMLElement>(null);
  const [offset, setOffset] = useState(0);

  useEffect(() => {
    let ticking = false;

    const handleScroll = () => {
      if (!ticking) {
        window.requestAnimationFrame(() => {
          if (sectionRef.current) {
            const sectionTop = sectionRef.current.offsetTop;
            const calculatedOffset = (window.scrollY - sectionTop + window.innerHeight) * 0.3;
            setOffset(calculatedOffset);
          }
          ticking = false;
        });
        ticking = true;
      }
    };

    handleScroll();
    window.addEventListener('scroll', handleScroll, { passive: true });
    window.addEventListener('resize', handleScroll);

    return () => {
      window.removeEventListener('scroll', handleScroll);
      window.removeEventListener('resize', handleScroll);
    };
  }, []);

  const row1Transform = `translateX(${offset - 200}px)`;
  const row2Transform = `translateX(${-(offset - 200)}px)`;

  return (
    <section
      ref={sectionRef}
      className="relative w-full bg-[#0C0C0C] pt-24 sm:pt-32 md:pt-40 pb-10 overflow-hidden select-none"
    >
      <div className="flex flex-col gap-3 w-full">
        {/* Row 1: Moves RIGHT on scroll */}
        <div
          className="flex gap-3 transition-transform ease-out"
          style={{
            transform: row1Transform,
            willChange: 'transform',
          }}
        >
          {ROW_1_IMAGES.map((src, idx) => (
            <div
              key={`r1-${idx}`}
              className="w-[420px] h-[270px] shrink-0 rounded-2xl overflow-hidden bg-[#16181D] shadow-lg hover:brightness-110 transition-all duration-300"
            >
              <img
                src={src}
                alt="3D Project Preview"
                loading="lazy"
                className="w-full h-full object-cover rounded-2xl pointer-events-none"
              />
            </div>
          ))}
        </div>

        {/* Row 2: Moves LEFT on scroll */}
        <div
          className="flex gap-3 transition-transform ease-out"
          style={{
            transform: row2Transform,
            willChange: 'transform',
          }}
        >
          {ROW_2_IMAGES.map((src, idx) => (
            <div
              key={`r2-${idx}`}
              className="w-[420px] h-[270px] shrink-0 rounded-2xl overflow-hidden bg-[#16181D] shadow-lg hover:brightness-110 transition-all duration-300"
            >
              <img
                src={src}
                alt="3D Project Preview"
                loading="lazy"
                className="w-full h-full object-cover rounded-2xl pointer-events-none"
              />
            </div>
          ))}
        </div>
      </div>
    </section>
  );
};
